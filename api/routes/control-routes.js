// Model performance (latency by model)
router.get('/metrics/model-performance', (req, res) => {
  // Aggregate from request log
  const byModel = {};
  for (const entry of orchestrator.requestLog) {
    if (entry.model && entry.latency_ms) {
      if (!byModel[entry.model]) byModel[entry.model] = { latencies: [], requests: 0 };
      byModel[entry.model].latencies.push(entry.latency_ms);
      byModel[entry.model].requests++;
    }
  }
  const summary = Object.entries(byModel).map(([model, data]) => {
    const sorted = data.latencies.sort((a, b) => a - b);
    const p50 = sorted[Math.floor(sorted.length * 0.5)];
    const p95 = sorted[Math.floor(sorted.length * 0.95)];
    const p99 = sorted[Math.floor(sorted.length * 0.99)];
    return { model, requests: data.requests, latency_p50: p50, latency_p95: p95, latency_p99: p99 };
  }).sort((a, b) => b.requests - a.requests);
  res.json(summary);
});

