// Auth middleware for sensitive control routes
// Requires either:
//   - X-Control-Token header matching the control token, or
//   - Or being on localhost (127.0.0.1 / ::1)
// The token comes from HIVV_CONTROL_TOKEN, or — if unset, which was the case
// in production (it was an empty string, so token auth simply never worked) —
// from api/.control-token (0600), generated by the operator.
function _loadControlToken() {
    if (process.env.HIVV_CONTROL_TOKEN) return process.env.HIVV_CONTROL_TOKEN;
    try {
        const t = require('fs').readFileSync(
            require('path').join(__dirname, '..', '.control-token'), 'utf8').trim();
        return t || '';
    } catch (_e) { return ''; }
}
const CONTROL_TOKEN = _loadControlToken();
async function requireControlAuth(req, res, next) {
    // Allow localhost without auth (for development)
    const ip = req.ip || req.connection?.remoteAddress || '';
    const isLocal = ip.includes('127.0.0.1') || ip.includes('::1') || ip.includes('localhost');
    if (isLocal) return next();

    // Check token (timing-safe comparison)
    const token = req.headers['x-control-token'] || req.query?.token;
    if (CONTROL_TOKEN && token) {
        const crypto = require('crypto');
        try {
            const a = Buffer.from(CONTROL_TOKEN);
            const b = Buffer.from(token);
            if (a.length === b.length && crypto.timingSafeEqual(a, b)) return next();
        } catch(e) {}
    }

    // Check if user is authenticated admin
    if (req.session?.userId) {
        // Verify user is admin/owner (check database)
        const { pool } = require('../server');
        if (pool) {
            try {
                const result = await pool.query('SELECT role FROM users WHERE id = $1', [req.session.userId]);
                if (result.rows[0]?.role === 'admin' || result.rows[0]?.role === 'owner') {
                    return next();
                }
            } catch(e) {}
        }
    }

    return res.status(401).json({ error: 'Unauthorized — admin access required' });
}

// Apply auth to all write operations
router.use((req, res, next) => {
    if (req.method === 'GET') return next(); // Read-only is public
    return requireControlAuth(req, res, next);
});

