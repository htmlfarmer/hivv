// ── shared update-envelope hardening ─────────────────────────────────────
// This tells every bee to download and execute a file, so it must never be
// able to point them off-hub:
//  1. only a hub-relative path is accepted (no scheme, no host, no '..');
//  2. the sha256 is computed from the bytes THIS hub actually serves, never
//     trusted from the caller (a caller-supplied hash must match, else error).
// Used by BOTH the per-bee push-update and the fleet-wide update-all.
function _updateEnvelope(url, sha256) {
  const rel = String(url || `/${(global.__HIVV_APP__ || 'hivv')}-cli.py`);
  if (!rel.startsWith('/') || /^[a-z][a-z0-9+.-]*:/i.test(rel) || rel.includes('..')) {
    return { ok: false, error: 'url must be a hub-relative path — external URLs are refused' };
  }
  let served = null;
  try {
    const f = require('path').join(__dirname, '..', '..', 'public_html', rel.replace(/^\//, ''));
    served = require('crypto').createHash('sha256').update(require('fs').readFileSync(f)).digest('hex');
  } catch (_e) {
    return { ok: false, error: `push target not found on this hub: ${rel}` };
  }
  if (sha256 && String(sha256).toLowerCase() !== served) {
    return { ok: false, error: `sha256 mismatch — caller said ${sha256}, hub serves ${served}` };
  }
  return { ok: true, rel, sha256: served };
}

// The version string a bee compares against — same recipe as server.js
// _cliVersion(): 0.2.<sha256-of-served-cli, first 8>.
function _hubCliVersion() {
  try {
    const fs = require('fs');
    const crypto = require('crypto');
    const p = require('path').join(__dirname, '..', '..', 'public_html', 'hivv-cli.py');
    return '0.2.' + crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex').slice(0, 8);
  } catch (_e) { return 'unknown'; }
}

// POST /api/control/agents/:nodeId/push-update — enqueue an `update_available`
// message into the node's inbox. Body: { version, url?, sha256? }
// The node will receive it on its next long-poll.
router.post('/agents/:nodeId/push-update', express.json(), (req, res) => {
  const nodeId = req.params.nodeId;
  const node = orchestrator.nodes.get(nodeId);
  if (!node) return res.status(404).json({ error: 'Node not found' });
  const { version, url, sha256 } = req.body || {};
  if (!version) return res.status(400).json({ error: 'version required' });

  const env = _updateEnvelope(url, sha256);
  if (!env.ok) return res.status(400).json({ error: env.error });

  const msg = {
    type: 'update_available',
    payload: {
      version,
      url: env.rel,
      sha256: env.sha256,
    },
    ts: Date.now(),
  };
  // Use the inbox store if available (InboxRoutes.inject(orch) wires it).
  if (typeof orchestrator.enqueueInbox === 'function') {
    const id = orchestrator.enqueueInbox(nodeId, msg);
    return res.json({ ok: true, id, message: msg });
  }
  return res.status(503).json({ error: 'inbox not initialized' });
});

// ── POST /api/control/update-all — the FLEET update button ───────────────
// Enqueues the hub's own CLI into every registered bee's inbox — one call
// instead of N (the mobile panel's "Update all", and any fleet rollout).
//
// WHY IT IS SAFE BY CONSTRUCTION:
//  * same envelope hardening as push-update per bee — hub-relative URL only,
//    sha256 computed from the bytes THIS hub serves;
//  * it never executes anything here — each bee runs the update through ITS
//    OWN review gate (static scan + LLM vote) and refuses a suspicious copy;
//  * `dry_run: true` plans without enqueueing, so a phone can preview the
//    blast radius (and the panel always previews before firing).
//
// Body: { dry_run?, url?, sha256? } — version defaults to the hub's own.
router.post('/update-all', express.json(), (req, res) => {
  const { dry_run, url, sha256 } = req.body || {};
  const env = _updateEnvelope(url, sha256);
  if (!env.ok) return res.status(400).json({ error: env.error });
  const version = _hubCliVersion();

  const pushed = [];
  const skipped = [];
  for (const node of orchestrator.nodes.values()) {
    const id = node.node_id || node.name || '?';
    // Use the SAME status computation /nodes shows (getNodeStatus derives
    // from heartbeat age), not the possibly-stale in-memory field — the
    // first dry_run reported 'pushed' to a bee that had been offline for
    // a day, because its cached status still said 'online'.
    let status = node.status;
    try {
      if (typeof orchestrator.getNodeStatus === 'function') {
        status = orchestrator.getNodeStatus(node);
      }
    } catch (_e) { /* keep the cached field */ }
    if (status === 'offline') {
      // A ghost registration: no heartbeat, no inbox consumer — and it can
      // never run `hivv update` anyway. Report it, don't pretend.
      skipped.push({ id, reason: 'offline' });
      continue;
    }
    if (dry_run) {
      pushed.push(id);
      continue;
    }
    try {
      const msg = {
        type: 'update_available',
        payload: { version, url: env.rel, sha256: env.sha256 },
        ts: Date.now(),
      };
      if (typeof orchestrator.enqueueInbox === 'function') {
        orchestrator.enqueueInbox(node.node_id, msg);
        pushed.push(id);
      } else {
        skipped.push({ id, reason: 'inbox not initialized' });
      }
    } catch (e) {
      skipped.push({ id, reason: String(e.message || e).slice(0, 80) });
    }
  }
  res.json({
    ok: true,
    dry_run: !!dry_run,
    version,
    sha256: env.sha256,
    url: env.rel,
    total: pushed.length + skipped.length,
    pushed,
    skipped,
  });
});

// ── POST /api/control/agents/:nodeId/repair ──────────────────────────────
// Enqueue a SIGNED, allowlisted repair plan into a bee's inbox
// (`hivv repair <bee> --op service_restart --unit llama.service`).
// The bee independently re-verifies the HMAC, ttl, nonce and op allowlist —
// this side only decides what may be requested and signs it with the node's
// own secret, so a forged plan can't be injected even with control access.
// `bootstrap_user_install` — THE ESCAPE HATCH for a box whose CLI is too old
// to update itself. A system-wide install (/usr/local/lib/hivv, root-owned)
// with a USER-scoped agent means the user can never write the install dir,
// and the old CLI dies on the .bak write — so the box can never self-heal
// (asher@wahi 2026-11-21/22: thirteen identical failed update rows). This
// op installs the CURRENT CLI into the user's OWN ~/.local install, which
// the user CAN write. It never escalates privilege and never touches the
// root-owned copy.
const REPAIR_OPS = new Set(['cli_update', 'agent_restart', 'reap_duplicates', 'service_restart', 'selftest',
                            'bootstrap_user_install']);
const REPAIR_UNITS = new Set(['llama.service', 'llama-server.service', 'ollama.service',
                              'mcp-bridge.service', 'mcp-web-server.service',
                              'kokoro-tts-server.service', 'whisper-stt-server.service']);

router.post('/agents/:nodeId/repair', express.json(), (req, res) => {
  const nodeId = req.params.nodeId;
  const node = orchestrator.nodes.get(nodeId);
  if (!node) return res.status(404).json({ error: 'Node not found' });
  if (!node.secret) {
    return res.status(409).json({ error: 'node not enrolled yet (no secret) — wait for its next heartbeat' });
  }
  const body = req.body || {};
  let ops = body.ops;
  if (!Array.isArray(ops) || ops.length < 1 || ops.length > 8) {
    return res.status(400).json({ error: 'ops must be an array of 1..8 actions', allowed: [...REPAIR_OPS] });
  }
  const clean = ops.map(o => {
    if (!o || typeof o !== 'object') return null;
    const name = String(o.op || '');
    if (!REPAIR_OPS.has(name)) return null;
    if (name === 'service_restart') {
      const unit = String(o.unit || '');
      if (!REPAIR_UNITS.has(unit)) return null;
      return { op: name, unit: unit };
    }
    // `force` is the operator's explicit, signature-covered authorization to
    // apply an update whose review verdict was "suspicious". Boolean only.
    if (name === 'cli_update') return { op: name, force: o.force === true };
    return { op: name };
  });
  if (clean.some(o => !o)) {
    return res.status(400).json({ error: 'unknown op or unit refused',
                                  allowed_ops: [...REPAIR_OPS], allowed_units: [...REPAIR_UNITS] });
  }
  const plan = {
    plan_id: 'rp_' + Date.now().toString(36) + Math.random().toString(36).slice(2, 8),
    ts: Math.floor(Date.now() / 1000),   // SECONDS — the bee compares against time.time()
    ttl_s: Math.min(Math.max(parseInt(body.ttl_s, 10) || 300, 60), 600),
    ops: clean,
    reason: String(body.reason || '').slice(0, 200),
  };
  // Must mirror the bee's canonical string exactly (see _repair_signature_ok):
  // int(ts) \n int(ttl_s) \n JSON(ops, keys sorted, no spaces).
  // JSON.stringify keeps INSERTION order — for {op, force} that yields
  // {"op":…,"force":…} while the bee's sort_keys() yields {"force":…,"op":…},
  // so every cli_update plan failed HMAC verification (masjid 2026-11-14).
  // Recursively sort keys before stringify to match Python's sort_keys=True.
  const sortedJson = (v) => {
    if (Array.isArray(v)) return '[' + v.map(sortedJson).join(',') + ']';
    if (v && typeof v === 'object')
      return '{' + Object.keys(v).sort().map(k => JSON.stringify(k) + ':' + sortedJson(v[k])).join(',') + '}';
    return JSON.stringify(v);
  };
  plan.sig = require('crypto').createHmac('sha256', String(node.secret))
    .update(`${plan.ts}\n${plan.ttl_s}\n${sortedJson(plan.ops)}`).digest('hex');

  if (typeof orchestrator.enqueueInbox !== 'function') {
    return res.status(503).json({ error: 'inbox not initialized' });
  }
  const id = orchestrator.enqueueInbox(nodeId, { type: 'repair', payload: plan, ts: Date.now() });
  console.log(`[REPAIR] ${nodeId} <- ${plan.plan_id} ${JSON.stringify(clean)} reason=${plan.reason || '-'}`);
  return res.json({ ok: true, id, plan_id: plan.plan_id, ttl_s: plan.ttl_s, ops: clean });
});

// ── POST /api/control/nodes/:id/quarantine — network-side stop / release ─────
// Shares ONE field with the crash-loop auto-detector (orchestrator register):
// auto-quarantine fires on ≥5 re-registers/10min; ONLY a human release clears
// it and re-arms the detector (charter: machines restrict, humans restore).
router.post('/nodes/:id/quarantine', express.json(), (req, res) => {
  const node = orchestrator.nodes.get(req.params.id);
  if (!node) return res.status(404).json({ error: 'Node not found' });
  const release = (req.body || {}).release === true;
  if (release) {
    node.quarantined = null;
    node.flap_events = [];
    if (node.status === 'quarantined') node.status = 'offline';   // next heartbeat re-lifts it
    try { orchestrator._saveNodes(); } catch (_e) {}
    console.log(`[QUAR] ${node.node_id} released by operator — detector re-armed`);
    return res.json({ ok: true, released: true, node: node.name });
  }
  const now = Date.now();
  node.quarantined = {
    by: 'operator',
    reason: String((req.body || {}).reason || 'operator quarantine').slice(0, 120),
    since: now,
    count: Array.isArray(node.flap_events) ? node.flap_events.length : 0,
  };
  node.status = 'quarantined';
  try { orchestrator._saveNodes(); } catch (_e) {}
  console.log(`[QUAR] ${node.node_id} quarantined by operator: ${node.quarantined.reason}`);
  res.json({ ok: true, quarantined: true, node: node.name });
});

