// POST /api/control/incidents — create a new incident (also called by background monitor)
router.post('/incidents', async (req, res) => {
  try {
    const { pool } = require('../server');
    if (!pool) return res.status(503).json({ error: 'database_unavailable' });
    const { incident_type, severity = 'medium', node_id, title, description, evidence = [] } = req.body;
    if (!incident_type || !node_id || !title) {
      return res.status(400).json({ error: 'incident_type, node_id, and title are required' });
    }
    // Don't duplicate active incidents for the same node+type
    const dup = await pool.query(
      "SELECT id FROM hivv_incidents WHERE node_id=$1 AND incident_type=$2 AND state='active' LIMIT 1",
      [node_id, incident_type]
    );
    if (dup.rows.length > 0) {
      return res.json({ duplicate: true, id: dup.rows[0].id });
    }
    const result = await pool.query(`
      INSERT INTO hivv_incidents (incident_type, severity, state, node_id, title, description, evidence)
      VALUES ($1, $2, 'active', $3, $4, $5, $6)
      RETURNING *
    `, [incident_type, severity, node_id, title, description || title, JSON.stringify(evidence)]);
    console.log(`[INCIDENT] ${severity} ${incident_type} on ${node_id}: ${title}`);
    res.status(201).json({ created: true, incident: result.rows[0] });
  } catch (err) {
    console.error('create incident error:', err.message);
    res.status(500).json({ error: 'could_not_create_incident', detail: err.message });
  }
});

// PATCH /api/control/incidents/:id — update/resolve an incident
router.patch('/incidents/:id', async (req, res) => {
  try {
    const { pool } = require('../server');
    if (!pool) return res.status(503).json({ error: 'database_unavailable' });
    const { state, resolution_notes, severity } = req.body;
    const { id } = req.params;
    const updates = [];
    const params = [];
    let idx = 1;
    if (state) { updates.push(`state = $${idx++}`); params.push(state); }
    if (severity) { updates.push(`severity = $${idx++}`); params.push(severity); }
    if (state === 'resolved' || state === 'dismissed') {
      updates.push(`resolved_at = NOW()`);
    }
    if (resolution_notes !== undefined) { updates.push(`resolution_notes = $${idx++}`); params.push(resolution_notes); }
    if (updates.length === 0) return res.status(400).json({ error: 'no fields to update' });
    params.push(id);
    const result = await pool.query(
      `UPDATE hivv_incidents SET ${updates.join(', ')} WHERE id = $${idx} RETURNING *`,
      params
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'incident not found' });
    res.json({ updated: true, incident: result.rows[0] });
  } catch (err) {
    console.error('update incident error:', err.message);
    res.status(500).json({ error: 'could_not_update_incident', detail: err.message });
  }
});

