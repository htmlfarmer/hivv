// ── Nodes endpoint cache + rate limiter ──────────────────────────────────────
// 10-second cache so 1000 concurrent `hivv nodes` calls hit one cached response.
// Per-IP rate limiter (60 req/min) prevents abuse from any single client.
const _nodesCache = { data: null, ts: 0 };
const NODES_CACHE_MS = 10_000;
const _rateHits = new Map();
function _rateLimit(key, max = 60, windowMs = 60_000) {
  const now = Date.now();
  const arr = (_rateHits.get(key) || []).filter(t => now - t < windowMs);
  arr.push(now);
  _rateHits.set(key, arr);
  return arr.length <= max;
}

// ── Ping cache — nodes measure RTT locally, POST to hub, hub caches 30s ─────
// Clients POST once per display cycle; all readers get cached pings.
// This means1000 clients only generate ~N pings total (one per node), not N×nodes.
const _pingCache = new Map(); // nodeId → { ms, ts }
const PING_TTL_MS = 30_000;

router.get('/ping', (req, res) => {
  const now = Date.now();
  const out = {};
  for (const [id, entry] of _pingCache) {
    if (now - entry.ts < PING_TTL_MS) out[id] = entry.ms;
  }
  res.json({ pings: out, cached: true });
});

router.post('/ping', express.json({ limit: '4kb' }), (req, res) => {
  const { node_id, ping_ms } = req.body || {};
  if (!node_id || typeof ping_ms !== 'number') {
    return res.status(400).json({ error: 'node_id and ping_ms required' });
  }
  _pingCache.set(String(node_id).slice(0, 64), {
    ms: Math.round(Math.max(0, Math.min(ping_ms, 30000))),
    ts: Date.now()
  });
  res.json({ ok: true });
});

// Periodic cleanup of stale ping entries
setInterval(() => {
  const now = Date.now();
  for (const [k, v] of _pingCache) {
    if (now - v.ts > PING_TTL_MS * 2) _pingCache.delete(k);
  }
  for (const [k, arr] of _rateHits) {
    const keep = arr.filter(t => now - t < 60_000);
    if (keep.length) _rateHits.set(k, keep); else _rateHits.delete(k);
  }
}, 60_000).unref();

