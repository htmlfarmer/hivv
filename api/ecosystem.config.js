// The gateway's location is DERIVED, never hardcoded: the repo moves (a new
// GitHub repo, a new clone path, a developer's laptop) and this file still
// points PM2 at the right directory.
const path = require('path');
const fs = require('fs');

const API_DIR = __dirname;                                  // .../api
const ROOT_DIR = path.resolve(API_DIR, '..');               // the repo root
const LOG_DIR = process.env.HIVV_LOG_DIR || path.join(ROOT_DIR, 'logs');
try { fs.mkdirSync(LOG_DIR, { recursive: true }); } catch (_e) { /* pm2 will say so */ }

module.exports = {
  apps: [{
    name: 'hivv-ai-gateway',
    script: 'server.js',
    cwd: API_DIR,
    instances: 1,
    exec_mode: 'fork',
    env: {
      NODE_ENV: 'production',
      PORT: 3011,
      // Local llama.cpp (gemma-4-E2B) on loopback:8090 — 8080 is Apache's.
      // Router probes /v1/models then calls /v1/chat/completions (OpenAI format).
      //
      // Second door: our own KwaaiNet node's 'shard api' on loopback:18090.
      // It resolves a covering block chain through the libp2p hivemind DHT per
      // request, so the answer may come from any node serving the model — the
      // compute comes from the network, not from this box. Run by the
      // kwaainet-shard-api systemd user unit.
      //
      // '?delegated=1' marks it as an endpoint that forwards to remote compute
      // rather than serving a local model, so the spare-time guard measures it
      // against a longer idle threshold (see router.js). Without it, the
      // guard read normal distributed-inference latency as 'the owner is
      // using it' and skipped the endpoint on every request.
      //
      // Both are LOCAL providers: they sit in the tryLocalAI path, which is
      // reached BEFORE any cloud provider, and they are excluded from the
      // cloud failover chain (router.js filters !isLocalProvider). Nothing
      // here can carry traffic to a cloud provider by accident.
      HIVV_LOCAL_ENDPOINTS: 'http://localhost:8090/v1/models,http://localhost:18090/v1/models?delegated=1',
      // LYRz settlement: honey earned by a node also becomes a portable LYRz
      // balance that follows the node across the ecosystem.
      LYRZ_API_URL: 'https://lyrz.org/api/v1',
      LYRZ_SITE_ID: 'hivv.org',
      // A real key never lives in the repository — same rule as the session secret
      // and control token below (commit 553c1fe). LYRZ_API_KEY was the one
      // exception and the pre-commit scanner caught it. The consumer,
      // api/lib/lyrz.js, already reads process.env.LYRZ_API_KEY, so nothing
      // else changes: without the operator file, settlement simply disables
      // itself with a warning instead of leaking a credential.
      LYRZ_API_KEY: process.env.LYRZ_API_KEY || (function () {
        try {
          return require('fs').readFileSync(__dirname + '/.lyrz-api-key', 'utf8').trim() || '';
        } catch (_e) { return ''; }
      })(),
      LYRZ_SETTLE_INTERVAL_MS: '300000',
      // How much LYRz one honey point is worth.
      HIVV_LYRZ_PER_HONEY: '0.1',
      // ── the toolkit (HIVV_TOOLKIT_PLAN.md §6) ─────────────────────────────
      // Web search is advertised by default as of 2026-11-24 — shipped WITH
      // the responsible-fetch layer (api/lib/polite.js: robots.txt obeyed,
      // per-host request floor, official API backends only). Its capability
      // is still `ask`: a non-loopback caller's first call mints a pending
      // grant a human approves; an operator on loopback runs un-gated.
      // Set HIVV_ENABLE_WEB_SEARCH=0 in the shell to hide it again.
      HIVV_ENABLE_WEB_SEARCH: process.env.HIVV_ENABLE_WEB_SEARCH || '1'
    },
    env_production: {
      DB_HOST: 'localhost',
      DB_PORT: 5432,
      DB_NAME: 'hivv',
      DB_USER: 'hivv',
      // The database password: the environment wins, then the operator's
      // 0600 file next to the code (so a fresh clone on a new box needs no
      // exported shell variables), then the placeholder — which works where
      // Postgres trusts localhost.
      HIVV_DB_PASSWORD: process.env.HIVV_DB_PASSWORD || (function () {
        try {
          return require('fs').readFileSync(__dirname + '/.db-password', 'utf8').trim() || '';
        } catch (_e) { return ''; }
      })() || 'CHANGE_ME_IN_PRODUCTION',
      // Session secret lives in a 0600 file (generated by the operator) so a
      // real value never has to be committed to this repo. Falls back to the
      // old placeholder only if the file is missing.
      HIVV_SESSION_SECRET: process.env.HIVV_SESSION_SECRET || (function () {
        try {
          return require('fs').readFileSync(__dirname + '/.session-secret', 'utf8').trim() || 'CHANGE_ME_IN_PRODUCTION';
        } catch (_e) { return 'CHANGE_ME_IN_PRODUCTION'; }
      })(),
      HIVV_CONTROL_TOKEN: process.env.HIVV_CONTROL_TOKEN || (function () {
        try {
          return require('fs').readFileSync(__dirname + '/.control-token', 'utf8').trim() || '';
        } catch (_e) { return ''; }
      })(),
      HIVV_ENCRYPTION_KEY: process.env.HIVV_ENCRYPTION_KEY || (function () {
        // A real key never lives in the repository. The operator generates one
        // into a 0600 file; without it the gateway refuses to start in
        // production rather than shipping a shared default.
        try {
          return require('fs').readFileSync(__dirname + '/.encryption-key', 'utf8').trim() || '';
        } catch (_e) { return ''; }
      })()
    },
    // Log into the vhost (daily-rotated as out-16__DATE.log) — do not let PM2
    // fall back to ~/.pm2/logs, which silently orphans the app's output from
    // everything that tails these files. `out.log` in older configs never existed.
    error_file: path.join(LOG_DIR, 'error-16.log'),
    out_file: path.join(LOG_DIR, 'out-16.log'),
    log_date_format: 'YYYY-MM-DD HH:mm:ss',
    max_memory_restart: '500M',
    restart_delay: 4000,
    max_restarts: 10,
    min_uptime: '10s'
  }]
};
